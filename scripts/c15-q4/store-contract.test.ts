test('Q4 failed event receipt insertion atomically rolls back status update',async()=>{
  const id='q4_rollback';await create(id);
  await db.exec("ALTER TABLE velmere_billing_private.lifecycle_events ADD CONSTRAINT q4_injected_failure CHECK (entitlement_id <> 'q4_rollback')");
  const result=await apply(id,'refund');assert.equal(result.ok,false);if(!result.ok)assert.equal(result.retryable,true);
  assert.equal((await state(id)).status,'active');assert.equal(await countEvents(id),0);
  await db.exec('ALTER TABLE velmere_billing_private.lifecycle_events DROP CONSTRAINT q4_injected_failure');
  assert.equal((await apply(id,'refund')).ok,true);
});
