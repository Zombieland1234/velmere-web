    const id=`q4_${event}_${status}`;assert.equal((await create(id)).ok,true);
    // Privileged test fixture setup only; this is not payment evidence.
    await db.query('UPDATE public.velmere_vlm_paid_entitlements SET status=$1 WHERE id=$2',[status,id]);
    const before=await state(id), result=await apply(id,event),target=expected[event][i];
