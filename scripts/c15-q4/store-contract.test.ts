async function create(id:string,changes:Record<string,unknown>={}) {
  const args={...record(id),...changes};
  const keys=Object.keys(args);
  const rows=await asRole<{result:Record<string,unknown>}>('service_role',
    `SELECT public.velmere_create_or_read_vlm_paid_entitlement(${keys.map((k,i)=>`${k} => $${i+1}`).join(',')}) AS result`,
    Object.values(args));
  return rows[0].result;
}
